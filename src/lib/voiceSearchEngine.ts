export function getVoiceResponse(
  parsed: VoiceParsedQuery,
  lang: 'ar' | 'en' = 'ar'
): string {
  if (parsed.intent === 'help') {
    return lang === 'ar' 
      ? 'كيف يمكنني مساعدتك؟ يمكنك البحث عن منتجات، متاجر، أو تصنيفات'
      : 'How can I help you? You can search for products, stores, or categories';
  }
  
  if (lang === 'ar') {
    return `جاري البحث عن "${parsed.cleanedText}"...`;
  } else {
    return `Searching for "${parsed.cleanedText}"...`;
  }
}

