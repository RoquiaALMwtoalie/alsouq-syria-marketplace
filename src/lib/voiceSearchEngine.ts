// 🔤 تطبيع النص العربي
// ============================================================

function normalizeArabicText(text: string): string {
  let normalized = text.toLowerCase().trim();
  normalized = normalized.replace(/َ|ً|ُ|ٌ|ِ|ٍ|ْ|ّ/g, '');
  normalized = normalized.replace(/[أإآ]/g, 'ا');
  normalized = normalized.replace(/ة/g, 'ه');
  normalized = normalized.replace(/ى/g, 'ي');
  return normalized;
}

// ============================================================
// 🇸🇾 تصحيح اللهجة السورية
// ============================================================

function correctSyrianDialect(text: string): string {
  let corrected = text;
  
  const words = corrected.split(' ');
  const correctedWords = words.map(word => {
    const lowerWord = word.toLowerCase().trim();
    
    // ابحث في القاموس السوري
    for (const [syrian, standard] of Object.entries(SYRIAN_DIALECT_CORRECTIONS)) {
      if (lowerWord === syrian.toLowerCase()) {
        return standard || ''; // إذا الجواب فاضي، شيلها
      }
    }
    
    return word;
  });
  
  corrected = correctedWords.filter(w => w.trim()).join(' ');
  
  return corrected;
}

