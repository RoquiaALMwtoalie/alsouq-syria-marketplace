// 🎯 الدالة الرئيسية
// ============================================================

export async function processVoiceSearch(
  text: string,
  lang: 'ar' | 'en' = 'ar'
): Promise<VoiceParsedQuery> {
  const startTime = Date.now();
  
  console.log('🎤 [VoiceEngine] Processing:', text);
  
  // 1️⃣ تصحيح اللهجة السورية
  let corrected = correctSyrianDialect(text);
  console.log('🇸🇾 After Syrian correction:', corrected);
  
  // 2️⃣ تصحيح الأخطاء الإملائية
  let cleaned = correctSpelling(corrected);
  
  // 3️⃣ تنظيف علامات الترقيم
  cleaned = cleaned.replace(/[.،,؛;؟?!:()"""''«»\-–—ـ…]/g, ' ');
  cleaned = cleaned.replace(/\s+/g, ' ').trim();
  
  if (!cleaned) {
    return {
      originalText: text,
      cleanedText: '',
      searchQuery: '',
      expandedQuery: '',
      intent: 'unknown',
      entities: {},
      confidence: 0,
      debug: { error: 'Empty query', original: text },
    };
  }
  
  // 4️⃣ بناء نص البحث النظيف (بدون stop words)
  const searchQuery = buildSearchQuery(text, cleaned);
  
  // 5️⃣ كشف النية
  const intent = detectIntent(cleaned);
  
  // 6️⃣ استخراج الكيانات
  const entities = extractEntities(cleaned);
  
  // 7️⃣ استخراج الكلمات
  const words = extractWords(cleaned);
  
  // 8️⃣ توسيع الكلمات (للعرض فقط، ليس للبحث)
  const expandedWords = expandKeywords(words);
  const expandedQuery = [...new Set(expandedWords)].join(' ');
  
  console.log('🎯 Intent:', intent);
  console.log('📊 Entities:', entities);
  console.log('🔍 Original words:', words);
  console.log('✅ Search query (clean):', searchQuery);
  console.log('🌐 Expanded query (display):', expandedQuery);
  console.log('⏱️ Execution time:', Date.now() - startTime, 'ms');
  
  // 9️⃣ حساب الثقة
  let confidence = 0.5;
  if (intent !== 'unknown') confidence += 0.2;
  if (Object.keys(entities).length > 0) confidence += 0.2;
  if (entities.productType || entities.brand) confidence += 0.1;
  confidence = Math.min(confidence, 1);
  
  return {
    originalText: text,
    cleanedText: cleaned,
    searchQuery,        // ✅ للبحث النظيف
    expandedQuery,      // ✅ للعرض/المرادفات
    intent,
    entities,
    confidence,
    debug: {
      words,
      expandedWords,
      executionTime: Date.now() - startTime,
    },
  };
}

